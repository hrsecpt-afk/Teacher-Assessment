/* ---------------------------------------------------------------------------
 * เครื่องคิดคะแนน
 * scores = { 'sectionId.itemIndex': ค่าที่กรอก }  (ระดับ หรือ คะแนนตรง)
 * ------------------------------------------------------------------------- */

function scoreKey(sectionId, index, groupId) {
  return groupId ? sectionId + '.' + groupId + '.' + index : sectionId + '.' + index;
}

/* คะแนนของข้อหนึ่ง ๆ หลังแปลงตามชนิด input */
function itemPoints(section, item, value) {
  var v = parseFloat(value);
  if (isNaN(v)) return 0;
  if (section.input === 'points') return Math.min(Math.max(v, 0), item.max);
  var levels = section.input === 'level5' ? 5 : 4;
  if (section.scaled) return item.max * v / levels;
  if (section.weighted && item.weight) return v * item.weight;
  return v;
}

/* คะแนนดิบสูงสุดของ section */
function sectionRawMax(section) {
  var max = 0, i;
  if (section.groups) {
    for (i = 0; i < section.groups.length; i++) max += groupRawMax(section, section.groups[i]);
    return max;
  }
  for (i = 0; i < section.items.length; i++) {
    max += itemPoints(section, section.items[i], section.input === 'points' ? section.items[i].max : (section.input === 'level5' ? 5 : 4));
  }
  return max;
}

function groupRawMax(section, group) {
  var max = 0;
  for (var i = 0; i < group.items.length; i++) {
    max += itemPoints(section, group.items[i], section.input === 'level5' ? 5 : 4);
  }
  return max;
}

/* คะแนนดิบที่ทำได้ของ section */
function sectionRaw(section, scores) {
  var sum = 0, i, j, g;
  if (section.groups) {
    for (i = 0; i < section.groups.length; i++) {
      g = section.groups[i];
      var gsum = 0;
      for (j = 0; j < g.items.length; j++) {
        gsum += itemPoints(section, g.items[j], scores[scoreKey(section.id, j, g.id)]);
      }
      /* แต่ละสมรรถนะแปลงเป็นคะแนนตามน้ำหนักของตัวเอง */
      var gmax = groupRawMax(section, g);
      sum += gmax > 0 ? (g.weight * gsum / gmax) : 0;
    }
    return sum;
  }
  for (i = 0; i < section.items.length; i++) {
    sum += itemPoints(section, section.items[i], scores[scoreKey(section.id, i)]);
  }
  return sum;
}

function sectionScore(section, scores) {
  return section.convert(sectionRaw(section, scores), section);
}

/* ผลรวมทั้งแบบฟอร์ม */
function evaluateForm(form, scores) {
  var result = { sections: {}, raw: {}, total: 0, percent: 0 };
  var i, s;
  if (form.weighted) {
    /* พนักงานราชการ: ถ่วงน้ำหนัก 80/20 */
    var weighted = 0;
    for (i = 0; i < form.sections.length; i++) {
      s = form.sections[i];
      var sc = sectionScore(s, scores);
      result.raw[s.id] = sectionRaw(s, scores);
      result.sections[s.id] = sc;
      weighted += sc * (s.weightPercent / 100);
    }
    result.total = weighted;
    result.percent = weighted;
  } else {
    for (i = 0; i < form.sections.length; i++) {
      s = form.sections[i];
      result.raw[s.id] = sectionRaw(s, scores);
      result.sections[s.id] = sectionScore(s, scores);
      result.total += result.sections[s.id];
    }
    result.percent = form.totalMax > 0 ? (result.total / form.totalMax) * 100 : 0;
  }
  result.grade = gradeOf(form.gradeScale, result.percent);
  result.passed = form.passPercent == null ? null : result.percent >= form.passPercent;
  if (form.hasContractDecision && form.contractRules) {
    for (i = 0; i < form.contractRules.length; i++) {
      if (result.percent >= form.contractRules[i].min) { result.contract = form.contractRules[i].label; break; }
    }
  }
  return result;
}

/* จำนวนข้อทั้งหมดของแบบฟอร์ม (ใช้เช็คความครบถ้วน) */
function formItemCount(form) {
  var n = 0;
  for (var i = 0; i < form.sections.length; i++) {
    var s = form.sections[i];
    if (s.groups) {
      for (var j = 0; j < s.groups.length; j++) n += s.groups[j].items.length;
    } else n += s.items.length;
  }
  return n;
}

function formAnsweredCount(form, scores) {
  var n = 0;
  for (var i = 0; i < form.sections.length; i++) {
    var s = form.sections[i];
    if (s.groups) {
      for (var j = 0; j < s.groups.length; j++) {
        for (var k = 0; k < s.groups[j].items.length; k++) {
          var v = scores[scoreKey(s.id, k, s.groups[j].id)];
          if (v !== undefined && v !== '' && v !== null) n++;
        }
      }
    } else {
      for (var m = 0; m < s.items.length; m++) {
        var v2 = scores[scoreKey(s.id, m)];
        if (v2 !== undefined && v2 !== '' && v2 !== null) n++;
      }
    }
  }
  return n;
}

